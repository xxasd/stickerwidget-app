const supportedLanguages = {
  en: "English",
  "zh-CN": "简体中文",
  "zh-TW": "繁體中文",
  ja: "日本語",
  ko: "한국어",
  de: "Deutsch"
};

function getLanguage() {
  // 1. Check localStorage
  const storedLang = localStorage.getItem('preferredLanguage');
  if (storedLang && translations[storedLang]) {
    return storedLang;
  }

  // 2. Check system language
  const lang = navigator.language || navigator.userLanguage;
  if (lang.startsWith('zh')) {
    // Check for Traditional Chinese variants
    if (lang === 'zh-TW' || lang === 'zh-HK' || lang === 'zh-MO' || lang === 'zh-Hant') {
      return 'zh-TW';
    }
    return 'zh-CN';
  }
  if (lang.startsWith('ja')) return 'ja';
  if (lang.startsWith('ko')) return 'ko';
  if (lang.startsWith('de')) return 'de';

  // 3. Fallback
  return 'en';
}

function setLanguage(lang) {
  if (!translations[lang]) return;

  localStorage.setItem('preferredLanguage', lang);
  updateContent(lang);
  updateSwitcherUI(lang);
}

function updateContent(lang) {
  const t = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (t[key]) {
      if (element.tagName === 'TITLE') {
        document.title = t[key];
      } else {
        element.innerHTML = t[key];
      }
    }
  });

  // Update App Store link
  const appStoreButton = document.querySelector('.app-store-button');
  if (appStoreButton && t.appStoreUrl) {
    appStoreButton.href = t.appStoreUrl;
  }

  document.documentElement.lang = lang;
}

function updateSwitcherUI(currentLang) {
  const btn = document.querySelector('.lang-btn');
  const options = document.querySelectorAll('.lang-option');

  if (btn) {
    btn.setAttribute('aria-label', `Change language, current: ${supportedLanguages[currentLang]}`);
  }

  options.forEach(opt => {
    if (opt.dataset.lang === currentLang) {
      opt.classList.add('active');
    } else {
      opt.classList.remove('active');
    }
  });
}

function initLanguageSwitcher() {
  // Remove existing switcher if any
  const existing = document.querySelector('.language-switcher');
  if (existing) existing.remove();

  const container = document.createElement('div');
  container.className = 'language-switcher';

  // Button
  const btn = document.createElement('button');
  btn.className = 'lang-btn';
  btn.innerHTML = `
    <svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
      <circle cx="12" cy="12" r="10"></circle>
      <line x1="2" y1="12" x2="22" y2="12"></line>
      <path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"></path>
    </svg>
  `;

  // Menu
  const menu = document.createElement('div');
  menu.className = 'lang-menu';

  Object.entries(supportedLanguages).forEach(([code, name]) => {
    const option = document.createElement('div');
    option.className = 'lang-option';
    option.dataset.lang = code;
    option.textContent = name;

    option.addEventListener('click', () => {
      setLanguage(code);
      menu.classList.remove('show');
    });

    menu.appendChild(option);
  });

  // Toggle menu
  btn.addEventListener('click', (e) => {
    e.stopPropagation();
    menu.classList.toggle('show');
  });

  // Close when clicking outside
  document.addEventListener('click', () => {
    menu.classList.remove('show');
  });

  menu.addEventListener('click', (e) => {
    e.stopPropagation();
  });

  container.appendChild(btn);
  container.appendChild(menu);
  document.body.appendChild(container);

  // Set initial state
  const currentLang = getLanguage();
  updateSwitcherUI(currentLang);
}

// Initialize
document.addEventListener('DOMContentLoaded', () => {
  initLanguageSwitcher();
  const lang = getLanguage();
  updateContent(lang);
});
